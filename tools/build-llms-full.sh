#!/usr/bin/env bash
# Concatenate the skill's documentation into docs/llms-full.txt (one plain-text file for AI crawlers).
# Usage: bash tools/build-llms-full.sh   (run from the repository root)
set -euo pipefail

cd "$(dirname "$0")/.."
OUT="docs/llms-full.txt"

FILES=(
  README.md
  README.zh-CN.md
  SKILL.md
  core/creative-method.md
  core/quality-rubric.md
  core/platform-copy.md
  styles/realistic/GUIDE.md
  styles/handdrawn/GUIDE.md
  examples/rea/README.md
  examples/rea/platform-copy.md
)

{
  echo "# explainer-video — full documentation bundle"
  echo
  echo "> Generated by tools/build-llms-full.sh. Source: https://github.com/bobobo2026/explainer-video"
  echo "> Canonical HTML: https://bobobo2026.github.io/explainer-video/"
  echo
  echo "Contents:"
  for f in "${FILES[@]}"; do echo "- $f"; done
  echo
  for f in "${FILES[@]}"; do
    [ -f "$f" ] || { echo "missing: $f" >&2; exit 1; }
    printf '\n\n---\n\n# >>> FILE: %s\n\n' "$f"
    cat "$f"
  done
} > "$OUT"

echo "wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
